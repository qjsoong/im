//! Generating `data/dict/pinyin.tsv` and `data/dict/syllables.txt`.
//!
//! The selection rules are frozen: other code reads the generated format, so
//! changes here must be mirrored in [`check`](super::check) and in the
//! documentation under `data/dict/`.

use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::fs;
use std::time::Instant;

use anyhow::{Context, Result, bail};

use super::sources::{self, LoadStats, Reading};
use super::{Paths, Record, compare_records, fetch, pinyin};

/// A two-character word is kept as soon as the jieba word list knows it.
///
/// Two-character words are the multi-character entries users reach most
/// often, so they get the laxer bar and the space budget goes to them first.
/// Frequencies are compared with unknown words counted as 0, so 1 means
/// membership in the jieba word list.
pub const MIN_TWO_CHAR_FREQ: u64 = 1;

/// A word of three or more characters is kept only when it occurs in the
/// jieba corpus at least this often.
pub const MIN_LONGER_FREQ: u64 = 3;

/// Size budget of `pinyin.tsv` in bytes (4 MiB).
///
/// [`build`] fails instead of writing a larger file, so the budget stays an
/// enforced property rather than an assumption.
pub const MAX_DICT_BYTES: u64 = 4 * 1024 * 1024;

/// Header of `pinyin.tsv`, documenting the frozen format.
///
/// The numbers that define curation and scoring are appended by
/// [`dict_parameters`] from the constants in this module, so the documented
/// thresholds cannot drift from the implementation.
const DICT_HEADER: &str = "\
# im pinyin dictionary
#
# Generated by `cargo run -p xtask -- dict build`. Do not edit by hand.
#
# One record per line, three TAB-separated fields: text, spelling, weight.
#
# text      Han-only word, that is characters in U+3400..U+4DBF,
#           U+4E00..U+9FFF or U+F900..U+FAFF; ASCII, digits, punctuation,
#           whitespace, kana and emoji never occur in a text field
# spelling  lowercase ASCII pinyin without tones, syllables separated by
#           single spaces; \"ü\" is written as \"v\", so 女 is nv, 略 is lve
#           and 绿 is lv
#           The number of syllables always equals the number of characters.
# weight    integer in 0..=65535; among records with the same spelling a
#           greater weight means a more common word
#
# weight = min(65535, round(1000 * ln(max(jieba_freq, 1)))
#              + single-character bonus + curated-reading bonus)
#   jieba_freq   frequency in the fxsjy/jieba word list, 1 when absent
#   the bonuses are listed under format parameters below
# The single-character bonus keeps single characters ahead of rare words;
# the curated bonus marks hand-checked readings.
#
# Selection: every single-character reading is kept. A two-character word is
# kept as soon as the jieba word list knows it, a longer word only when the
# corpus shows that it matters: two-character words are the multi-character
# entries users reach most often, so they get the laxer bar. `dict build`
# refuses to write a file above the size budget below.
#
# Records are deduplicated on (text, spelling) keeping the greatest weight,
# then ordered by spelling (byte order), weight descending, then text (byte
# order), so regenerating from the same sources is reproducible.
#
# format parameters:
";

/// Header of `syllables.txt`.
const SYLLABLES_HEADER: &str = "\
# pinyin syllables used by pinyin.tsv, one per line, in byte order
#
# Generated by `cargo run -p xtask -- dict build`. Do not edit by hand.
";

/// What [`build`] wrote.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Summary {
    /// Records written to `pinyin.tsv`.
    pub records: usize,
    /// Size of `pinyin.tsv` in bytes.
    pub bytes: u64,
    /// Records whose text is a single character.
    pub single_char: usize,
    /// Distinct pinyin syllables.
    pub syllables: usize,
}

/// Build both dictionary files from the downloaded sources.
pub fn build(paths: &Paths) -> Result<Summary> {
    let started = Instant::now();
    fetch::ensure_fetched(paths)?;

    let frequencies = sources::load_frequencies(&paths.source(fetch::JIEBA))?;
    let (curated, curated_stats) =
        sources::load_curated_readings(&paths.source(fetch::PHRASE_CURATED))?;
    let (char_readings, char_stats) =
        sources::load_char_readings(&paths.source(fetch::PINYIN_DATA))?;
    let (phrase_readings, phrase_stats) =
        sources::load_phrase_readings(&paths.source(fetch::PHRASE_LARGE))?;

    let mut best: BTreeMap<(String, String), u16> = BTreeMap::new();
    for reading in &char_readings {
        let weight = weight_of(&frequencies, &curated, reading, true);
        keep(&mut best, reading, weight);
    }

    let mut kept_two_char = 0;
    let mut kept_longer = 0;
    for reading in &phrase_readings {
        // Unknown words count as 0 here, so `MIN_TWO_CHAR_FREQ` of 1 means
        // "the jieba word list knows the word".
        let frequency = frequencies.get(&reading.text).copied();
        if !is_kept_word(&reading.text, frequency) {
            continue;
        }
        if reading.text.chars().count() == 2 {
            kept_two_char += 1;
        } else {
            kept_longer += 1;
        }
        let weight = weight_of(&frequencies, &curated, reading, false);
        keep(&mut best, reading, weight);
    }

    let mut records: Vec<Record> = best
        .into_iter()
        .map(|((text, spelling), weight)| Record {
            text,
            spelling,
            weight,
        })
        .collect();
    sort_records(&mut records);

    let syllables = collect_syllables(&records);
    let dict_text = render_dict(&records);
    let syllables_text = render_syllables(&syllables);

    let bytes = dict_text.len() as u64;
    if bytes > MAX_DICT_BYTES {
        bail!(
            "the dictionary would be {bytes} bytes, above the {MAX_DICT_BYTES} byte \
             budget; raise the curation thresholds in xtask/src/dict/build.rs"
        );
    }

    let data_dir = paths
        .dict
        .parent()
        .context("the dictionary path has no parent directory")?;
    fs::create_dir_all(data_dir)
        .with_context(|| format!("failed to create {}", data_dir.display()))?;
    fs::write(&paths.dict, dict_text.as_bytes())
        .with_context(|| format!("failed to write {}", paths.dict.display()))?;
    fs::write(&paths.syllables, syllables_text.as_bytes())
        .with_context(|| format!("failed to write {}", paths.syllables.display()))?;

    let summary = Summary {
        records: records.len(),
        bytes,
        single_char: records
            .iter()
            .filter(|record| record.text.chars().count() == 1)
            .count(),
        syllables: syllables.len(),
    };
    report(
        paths,
        &summary,
        &char_stats,
        &phrase_stats,
        &curated_stats,
        (kept_two_char, kept_longer),
    );
    eprintln!("dict: build took {:.2}s", started.elapsed().as_secs_f64());
    Ok(summary)
}

/// Sort records into the canonical order of the file format.
pub fn sort_records(records: &mut [Record]) {
    records.sort_by(compare_records);
}

/// Smallest jieba frequency that makes a multi-character word worth keeping.
///
/// Callers look the frequency up with "unknown counts as 0", so
/// [`MIN_TWO_CHAR_FREQ`] of 1 means "the jieba word list knows the word".
pub fn min_frequency(text: &str) -> u64 {
    if text.chars().count() == 2 {
        MIN_TWO_CHAR_FREQ
    } else {
        MIN_LONGER_FREQ
    }
}

/// Whether a multi-character word earns a record in the dictionary.
///
/// `frequency` is the jieba frequency of `text`, or `None` when the corpus
/// does not know the word.
pub fn is_kept_word(text: &str, frequency: Option<u64>) -> bool {
    frequency.unwrap_or(0) >= min_frequency(text)
}

/// Insert a reading, keeping the greatest weight for its `(text, spelling)`.
fn keep(best: &mut BTreeMap<(String, String), u16>, reading: &Reading, weight: u16) {
    let key = (reading.text.clone(), reading.spelling.clone());
    best.entry(key)
        .and_modify(|current| *current = (*current).max(weight))
        .or_insert(weight);
}

/// Score one reading against the jieba frequencies and curated readings.
fn weight_of(
    frequencies: &HashMap<String, u64>,
    curated: &HashMap<String, HashSet<String>>,
    reading: &Reading,
    single_char: bool,
) -> u16 {
    pinyin::weight(
        frequency_of(frequencies, &reading.text),
        single_char,
        is_curated(curated, reading),
    )
}

/// Jieba frequency of `text`, or 1 when the corpus does not know the word.
fn frequency_of(frequencies: &HashMap<String, u64>, text: &str) -> u64 {
    frequencies.get(text).copied().unwrap_or(1)
}
/// Whether the hand-curated upstream data contains this exact reading.
fn is_curated(curated: &HashMap<String, HashSet<String>>, reading: &Reading) -> bool {
    curated
        .get(&reading.text)
        .is_some_and(|spellings| spellings.contains(&reading.spelling))
}

/// Collect the distinct syllables of all spellings.
fn collect_syllables(records: &[Record]) -> BTreeSet<String> {
    let mut syllables = BTreeSet::new();
    for record in records {
        for syllable in pinyin::syllables(&record.spelling) {
            syllables.insert(syllable.to_owned());
        }
    }
    syllables
}

/// Render the dictionary file, header included.
fn render_dict(records: &[Record]) -> String {
    let parameters = dict_parameters();
    let capacity = records.len() * 24 + DICT_HEADER.len() + parameters.len();
    let mut out = String::with_capacity(capacity);
    out.push_str(DICT_HEADER);
    out.push_str(&parameters);
    for record in records {
        out.push_str(&record.text);
        out.push('\t');
        out.push_str(&record.spelling);
        out.push('\t');
        out.push_str(&record.weight.to_string());
        out.push('\n');
    }
    out
}

/// Render the syllable list file, header included.
fn render_syllables(syllables: &BTreeSet<String>) -> String {
    let mut out = String::with_capacity(SYLLABLES_HEADER.len() + syllables.len() * 8);
    out.push_str(SYLLABLES_HEADER);
    for syllable in syllables {
        out.push_str(syllable);
        out.push('\n');
    }
    out
}

/// Fill the header template with the constants that define the format.
fn dict_parameters() -> String {
    format!(
        "#   single-character bonus    {single}\n\
         #   curated-reading bonus     {curated}\n\
         #   two-character words       jieba_freq >= {two}\n\
         #   longer words              jieba_freq >= {longer}\n\
         #   size budget               {budget} bytes (4 MiB)\n\
         #\n\
         # Sources: mozillazg/pinyin-data, mozillazg/phrase-pinyin-data and\n\
         # fxsjy/jieba, all MIT licensed. See data/dict/NOTICE.md for\n\
         # attribution and data/dict/README.md for the regeneration steps.\n",
        single = pinyin::SINGLE_CHAR_BONUS,
        curated = pinyin::CURATED_BONUS,
        two = MIN_TWO_CHAR_FREQ,
        longer = MIN_LONGER_FREQ,
        budget = MAX_DICT_BYTES,
    )
}

/// Print what the build read, kept and wrote.
fn report(
    paths: &Paths,
    summary: &Summary,
    char_stats: &LoadStats,
    phrase_stats: &LoadStats,
    curated_stats: &LoadStats,
    kept_multi_char: (usize, usize),
) {
    for (label, stats) in [
        ("char readings", char_stats),
        ("phrase readings", phrase_stats),
        ("curated readings", curated_stats),
    ] {
        eprintln!(
            "dict: {label}: {} kept from {} data lines ({} lines rejected)",
            stats.readings, stats.data_lines, stats.rejected_lines
        );
    }
    eprintln!(
        "dict: multi-character records: {} with 2 characters (jieba frequency >= \
         {MIN_TWO_CHAR_FREQ}), {} with 3 or more (frequency >= {MIN_LONGER_FREQ})",
        kept_multi_char.0, kept_multi_char.1
    );
    eprintln!(
        "dict: wrote {} and {}",
        paths.dict.display(),
        paths.syllables.display()
    );
    eprintln!(
        "dict: {} records, {} single-character, {} syllables, {} bytes ({:.2} MiB)",
        summary.records,
        summary.single_char,
        summary.syllables,
        summary.bytes,
        summary.bytes as f64 / (1024.0 * 1024.0)
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reading(text: &str, spelling: &str) -> Reading {
        Reading {
            text: text.to_owned(),
            spelling: spelling.to_owned(),
        }
    }

    fn record(text: &str, spelling: &str, weight: u16) -> Record {
        Record {
            text: text.to_owned(),
            spelling: spelling.to_owned(),
            weight,
        }
    }

    #[test]
    fn deduplication_keeps_the_greatest_weight() {
        let mut best = BTreeMap::new();
        keep(&mut best, &reading("中国", "zhong guo"), 100);
        keep(&mut best, &reading("中国", "zhong guo"), 500);
        keep(&mut best, &reading("中国", "zhong guo"), 300);
        keep(&mut best, &reading("中国", "zhong guo2"), 1);
        assert_eq!(best.len(), 2);
        assert_eq!(best[&("中国".to_owned(), "zhong guo".to_owned())], 500);
    }

    #[test]
    fn records_sort_by_spelling_then_weight_then_text() {
        let mut records = vec![
            record("乙", "yi", 10),
            record("你", "ni", 7),
            record("一", "yi", 20),
            record("衣", "yi", 10),
        ];
        sort_records(&mut records);
        let texts: Vec<&str> =
            records.iter().map(|record| record.text.as_str()).collect();
        assert_eq!(texts, ["你", "一", "乙", "衣"]);
    }

    #[test]
    fn sorting_does_not_depend_on_input_order() {
        let mut forwards = vec![
            record("一", "yi", 20),
            record("衣", "yi", 10),
            record("乙", "yi", 10),
            record("啊", "a", 1),
            record("你", "ni", 7),
        ];
        let mut backwards: Vec<Record> = forwards.iter().rev().cloned().collect();
        sort_records(&mut forwards);
        sort_records(&mut backwards);
        assert_eq!(forwards, backwards);
        assert_eq!(render_dict(&forwards), render_dict(&backwards));
    }

    #[test]
    fn rendered_dictionary_is_deterministic_and_documented() {
        let mut records = vec![record("一", "yi", 20), record("啊", "a", 1)];
        sort_records(&mut records);
        let text = render_dict(&records);
        assert_eq!(text, render_dict(&records));
        assert!(text.contains("# Selection: every single-character reading is kept."));
        assert!(text.contains(&format!("jieba_freq >= {MIN_TWO_CHAR_FREQ}")));
        assert!(text.contains(&format!("jieba_freq >= {MIN_LONGER_FREQ}")));
        assert!(text.contains(&format!("{MAX_DICT_BYTES} bytes")));
        assert!(text.contains(&format!("bonus    {}", pinyin::SINGLE_CHAR_BONUS)));
        assert!(text.ends_with("一\tyi\t20\n"));
        assert!(text.lines().count() > 30, "header documents the format");
    }

    #[test]
    fn curation_thresholds_favour_two_character_words() {
        assert_eq!(min_frequency("一"), MIN_LONGER_FREQ);
        assert_eq!(min_frequency("中国"), MIN_TWO_CHAR_FREQ);
        assert_eq!(min_frequency("一丁点儿"), MIN_LONGER_FREQ);
        assert!(min_frequency("中国") < min_frequency("一丁点儿"));

        assert!(is_kept_word("中国", Some(1)));
        assert!(is_kept_word("中国", Some(2)));
        assert!(!is_kept_word("中国", None));
        assert!(!is_kept_word("一丁点儿", Some(2)));
        assert!(is_kept_word("一丁点儿", Some(3)));
    }

    #[test]
    fn syllable_list_is_sorted_and_unique() {
        let records = vec![record("中国", "zhong guo", 1), record("一", "yi", 2)];
        let syllables = collect_syllables(&records);
        let listed: Vec<&str> = syllables.iter().map(String::as_str).collect();
        assert_eq!(listed, ["guo", "yi", "zhong"]);
        let text = render_syllables(&syllables);
        assert!(text.starts_with("# pinyin syllables"));
        assert!(text.ends_with("zhong\n"));
    }

    #[test]
    fn weights_reward_frequency_and_single_characters() {
        let frequencies: HashMap<String, u64> =
            [("一".to_owned(), 217_830u64), ("中国".to_owned(), 8_000)].into();
        let curated: HashMap<String, HashSet<String>> =
            [("中国".to_owned(), HashSet::from(["zhong guo".to_owned()]))].into();

        let character = weight_of(&frequencies, &curated, &reading("一", "yi"), true);
        let word =
            weight_of(&frequencies, &curated, &reading("中国", "zhong guo"), false);
        let unknown = weight_of(&frequencies, &curated, &reading("犇", "ben"), true);
        let unknown_word =
            weight_of(&frequencies, &curated, &reading("犇犇", "ben ben"), false);

        assert_eq!(word, pinyin::weight(8_000, false, true));
        assert!(character > word, "common character outranks common word");
        assert!(unknown > unknown_word, "rare character outranks rare word");
        assert_eq!(unknown_word, 0);
    }
}
